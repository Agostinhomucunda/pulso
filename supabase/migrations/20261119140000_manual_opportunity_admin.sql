-- PULSO public-card access controls and manual opportunity administration.
-- Apply only through the Supabase SQL Editor after reviewing this migration.
-- Additive only: existing opportunities and users are not deleted.

alter table public.opportunities
  add column if not exists public_summary text,
  add column if not exists image_rights_confirmed boolean not null default false,
  add column if not exists collection_method text not null default 'manual',
  add column if not exists created_by uuid references auth.users(id) on delete set null,
  add column if not exists updated_by uuid references auth.users(id) on delete set null,
  add column if not exists reviewed_by uuid references auth.users(id) on delete set null,
  add column if not exists reviewed_at timestamptz,
  add column if not exists published_by uuid references auth.users(id) on delete set null,
  add column if not exists posted_at timestamptz,
  add column if not exists withdrawn_by uuid references auth.users(id) on delete set null,
  add column if not exists withdrawn_at timestamptz;

alter table public.organizations
  add column if not exists logo_rights_confirmed boolean not null default false,
  add column if not exists logo_source_url text;

alter table public.opportunities
  drop constraint if exists opportunities_collection_method_check;
alter table public.opportunities
  add constraint opportunities_collection_method_check
  check (collection_method in ('manual', 'automatic'));

create table if not exists public.opportunity_admin_audit (
  id bigint generated by default as identity primary key,
  opportunity_id uuid references public.opportunities(id) on delete set null,
  actor_user_id uuid references auth.users(id) on delete set null,
  action text not null check (action in ('created', 'updated')),
  occurred_at timestamptz not null default now(),
  before_state jsonb,
  after_state jsonb not null
);

create index if not exists opportunity_admin_audit_opportunity_idx
  on public.opportunity_admin_audit (opportunity_id, occurred_at desc);

alter table public.opportunity_admin_audit enable row level security;
drop policy if exists opportunity_admin_audit_admin_read on public.opportunity_admin_audit;
create policy opportunity_admin_audit_admin_read
  on public.opportunity_admin_audit for select to authenticated
  using (public.is_pulso_admin());
revoke all on public.opportunity_admin_audit from anon, authenticated;
grant select on public.opportunity_admin_audit to authenticated;

-- Visitors may use only this fixed, capped public-card RPC. They cannot select
-- full opportunity rows or paginate the complete catalog through PostgREST.
revoke select on public.opportunities from public, anon;
revoke select on public.organizations from public, anon;
drop function if exists public.public_opportunity_cards(text, text);
create function public.public_opportunity_cards(
  p_category text default null,
  p_search text default null
)
returns table (
  id uuid,
  title text,
  public_summary text,
  category text,
  sector text,
  province text,
  municipality text,
  vacancies integer,
  application_deadline date,
  published_at timestamptz,
  source_name text,
  source_url text,
  application_url text,
  image_url text,
  image_source_url text,
  image_rights_confirmed boolean,
  verification_status text,
  organization jsonb,
  total_count bigint
)
language sql
stable
security definer
set search_path = ''
as $$
  with eligible as (
    select
      o.id, o.title, o.public_summary, o.category, o.sector, o.province,
      o.municipality, o.vacancies, o.application_deadline, o.published_at,
      o.source_name, o.source_url, o.application_url,
      case when o.image_rights_confirmed and o.image_url ~* '^https://' and o.image_source_url ~* '^https://' then o.image_url else null end as image_url,
      case when o.image_rights_confirmed and o.image_url ~* '^https://' and o.image_source_url ~* '^https://' then o.image_source_url else null end as image_source_url,
      coalesce(o.image_rights_confirmed and o.image_url ~* '^https://' and o.image_source_url ~* '^https://', false) as image_rights_confirmed, o.verification_status,
      jsonb_build_object(
        'name', org.name,
        'logo_url', case when org.logo_rights_confirmed and org.logo_url ~* '^https://' and org.logo_source_url ~* '^https://' then org.logo_url else null end,
        'logo_source_url', case when org.logo_rights_confirmed and org.logo_source_url ~* '^https://' then org.logo_source_url else null end,
        'logo_rights_confirmed', coalesce(org.logo_rights_confirmed and org.logo_source_url ~* '^https://', false),
        'official_website', org.official_website,
        'verification_status', org.verification_status,
        'sector', org.sector
      ) as organization,
      o.created_at
    from public.opportunities o
    join public.organizations org on org.id = o.organization_id
    join public.sources s on s.id = o.source_id
    where o.status = 'published'
      and o.verification_status = 'verified'
      and o.source_url ~* '^https://'
      and (o.application_url is null or o.application_url ~* '^https://')
      and org.verification_status = 'verified'
      and s.access_status = 'authorized' and s.active = true
      and s.visible_publicly = true and s.source_url ~* '^https://'
      and (p_category is null or o.category = p_category)
      and (
        p_search is null or btrim(p_search) = '' or
        strpos(lower(concat_ws(' ', o.title, o.public_summary, o.source_name, org.name,
          o.category, o.sector, o.province, o.municipality)), lower(btrim(p_search))) > 0
      )
  ), ranked as (
    select eligible.*, count(*) over () as catalog_count
    from eligible
    order by published_at desc nulls last, created_at desc
    limit 5
  )
  select
    ranked.id, ranked.title, ranked.public_summary, ranked.category, ranked.sector,
    ranked.province, ranked.municipality, ranked.vacancies, ranked.application_deadline,
    ranked.published_at, ranked.source_name, ranked.source_url, ranked.application_url,
    ranked.image_url, ranked.image_source_url, ranked.image_rights_confirmed,
    ranked.verification_status, ranked.organization, ranked.catalog_count
  from ranked
  order by ranked.published_at desc nulls last, ranked.created_at desc;
$$;
revoke all on function public.public_opportunity_cards(text, text) from public;
grant execute on function public.public_opportunity_cards(text, text) to anon, authenticated;

-- The public organization directory has its own narrow RPC so anonymous clients
-- cannot retrieve unapproved logo URLs or internal organization fields.
drop function if exists public.public_verified_organizations();
create function public.public_verified_organizations()
returns table (
  id uuid,
  name text,
  sector text,
  province text,
  municipality text,
  official_website text,
  logo_url text,
  logo_source_url text,
  logo_rights_confirmed boolean,
  verification_status text
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    org.id, org.name, org.sector, org.province, org.municipality,
    org.official_website,
    case when org.logo_rights_confirmed and org.logo_url ~* '^https://' and org.logo_source_url ~* '^https://' then org.logo_url else null end,
    case when org.logo_rights_confirmed and org.logo_url ~* '^https://' and org.logo_source_url ~* '^https://' then org.logo_source_url else null end,
    coalesce(org.logo_rights_confirmed and org.logo_url ~* '^https://' and org.logo_source_url ~* '^https://', false),
    org.verification_status
  from public.organizations org
  where org.verification_status = 'verified'
  order by org.name
  limit 12;
$$;
revoke all on function public.public_verified_organizations() from public;
grant execute on function public.public_verified_organizations() to anon, authenticated;

create or replace function public.prepare_pulso_opportunity_admin_fields()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  source_is_authorized boolean;
  organization_is_verified boolean;
begin
  if tg_op = 'INSERT' then
    new.created_by := auth.uid();
    new.collection_method := coalesce(new.collection_method, 'manual');
  else
    new.created_by := old.created_by;
    new.created_at := old.created_at;
  end if;

  new.updated_by := auth.uid();
  new.updated_at := now();

  if tg_op = 'INSERT' then
    if new.verification_status = 'verified' then
      new.reviewed_by := auth.uid();
      new.reviewed_at := now();
    end if;
  elsif new.verification_status = 'verified'
        and old.verification_status is distinct from 'verified' then
    new.reviewed_by := auth.uid();
    new.reviewed_at := now();
  elsif old.reviewed_by is not null and new.verification_status = 'verified' then
    new.reviewed_by := old.reviewed_by;
    new.reviewed_at := old.reviewed_at;
  end if;

  if tg_op = 'INSERT' then
    if new.status = 'published' then
      raise exception 'Create an opportunity as a draft or pending review before publishing.';
    end if;
  elsif new.status = 'published' then
    if new.verification_status <> 'verified' then
      raise exception 'An opportunity must be verified before publication.';
    end if;
    if coalesce(new.title, '') = '' or coalesce(new.source_name, '') = ''
       or coalesce(new.source_url, '') !~* '^https://' then
      raise exception 'A title, source name and HTTPS source URL are required before publication.';
    end if;
    if new.application_url is not null and new.application_url !~* '^https://' then
      raise exception 'The application URL must use HTTPS.';
    end if;
    if new.image_url is not null and (
      new.image_url !~* '^https://'
      or coalesce(new.image_source_url, '') !~* '^https://'
      or new.image_rights_confirmed is not true
    ) then
      raise exception 'An opportunity image requires HTTPS URLs and confirmed image rights.';
    end if;
    if new.organization_id is null then
      raise exception 'A verified organization must be associated before publication.';
    end if;
    select exists (
      select 1 from public.organizations
      where id = new.organization_id and verification_status = 'verified'
    ) into organization_is_verified;
    if not organization_is_verified then
      raise exception 'The associated organization must be verified before publication.';
    end if;
    if new.source_id is null then
      raise exception 'An authorized source record is required before publication.';
    end if;
    select exists (
      select 1 from public.sources
      where id = new.source_id and access_status = 'authorized' and active = true
    ) into source_is_authorized;
    if not source_is_authorized then
      raise exception 'The selected source must be active and authorized before publication.';
    end if;
    if old.status is distinct from 'published' then
      new.published_by := auth.uid();
      new.posted_at := now();
      new.withdrawn_by := null;
      new.withdrawn_at := null;
    end if;
  else
    if tg_op = 'UPDATE' and old.status = 'published'
       and new.status is distinct from 'published' then
      new.withdrawn_by := auth.uid();
      new.withdrawn_at := now();
    end if;
  end if;

  return new;
end;
$$;

revoke all on function public.prepare_pulso_opportunity_admin_fields() from public, anon, authenticated;
drop trigger if exists prepare_pulso_opportunity_admin_fields on public.opportunities;
create trigger prepare_pulso_opportunity_admin_fields
  before insert or update on public.opportunities
  for each row execute function public.prepare_pulso_opportunity_admin_fields();

create or replace function public.audit_pulso_opportunity_admin_changes()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.opportunity_admin_audit (
      opportunity_id, actor_user_id, action, after_state
    ) values (
      new.id, auth.uid(), 'created', to_jsonb(new)
    );
    return new;
  end if;

  insert into public.opportunity_admin_audit (
    opportunity_id, actor_user_id, action, before_state, after_state
  ) values (
    new.id, auth.uid(), 'updated', to_jsonb(old), to_jsonb(new)
  );
  return new;
end;
$$;

revoke all on function public.audit_pulso_opportunity_admin_changes() from public, anon, authenticated;
drop trigger if exists audit_pulso_opportunity_admin_changes on public.opportunities;
create trigger audit_pulso_opportunity_admin_changes
  after insert or update on public.opportunities
  for each row execute function public.audit_pulso_opportunity_admin_changes();
